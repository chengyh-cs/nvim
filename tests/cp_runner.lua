vim.opt.rtp:prepend(vim.fn.getcwd())
local root = vim.fn.tempname() .. " cp tests"
vim.fn.mkdir(root, "p")
local count = 0
local function eq(actual, expected)
	assert(vim.deep_equal(actual, expected), vim.inspect(actual) .. " ~= " .. vim.inspect(expected))
end
local function file(name, lines)
	local path = root .. "/" .. name
	vim.fn.writefile(lines, path)
	return path
end
local function test(name, fn)
	local ok, err = pcall(fn)
	if not ok then
		io.stderr:write("FAIL " .. name .. ": " .. tostring(err) .. "\n")
		vim.fn.delete(root, "rf")
		vim.cmd("cquit 1")
	end
	count = count + 1
	print("PASS " .. name)
end
local runner
test("runner is available", function()
	local ok, module = pcall(require, "cp_runner.runner")
	assert(ok, "cp_runner.runner has not been implemented")
	runner = module
end)
local function run(path, ft, input, opts)
	local result
	local handle = runner.start(path, ft, input, opts or {}, function(value)
		result = value
	end)
	assert(vim.wait(15000, function() return result ~= nil end, 10), "process did not finish")
	return result, handle
end
local py = file("sum with spaces.py", { "import sys", "print(sum(map(int, sys.stdin.read().split())))" })
test("Python receives multiline stdin and EOF", function()
	local result = run(py, "python", "1 2\n3 4\n")
	eq(result.stdout, "10\n")
	eq(result.code, 0)
end)
test("empty input closes stdin", function()
	eq(run(py, "python", "").stdout, "0\n")
end)
test("C++ compiles and runs from a path with spaces", function()
	local cpp = file("sum with spaces.cpp", {
		"#include <iostream>",
		"int main() { long long x, s=0; while(std::cin >> x) s+=x; std::cout << s << '\\n'; }",
	})
	local result, handle = run(cpp, "cpp", "2 3\n7\n")
	eq(result.stdout, "12\n")
	eq(result.code, 0)
	assert(vim.fn.isdirectory(handle.temp_dir) == 0, "temporary executable leaked")
end)
test("compile errors are returned without running", function()
	local result = run(file("broken.cpp", { "this is not C++" }), "cpp", "")
	eq(result.phase, "compile")
	assert(result.code ~= 0 and #result.stderr > 0)
end)
test("runtime errors preserve stdout and stderr separately", function()
	local result = run(file("error.py", { "print('before')", "raise ValueError('bad input')" }), "python", "")
	eq(result.stdout, "before\n")
	assert(result.code ~= 0 and result.stderr:find("bad input", 1, true))
end)
test("program runs in the source directory", function()
	file("data.txt", { "local data" })
	local result = run(file("relative.py", { "print(open('data.txt').read().strip())" }), "python", "")
	eq(result.stdout, "local data\n")
end)
local loop = file("loop.py", { "while True: pass" })
test("infinite loop times out", function()
	eq(run(loop, "python", "", { timeout = 100 }).reason, "timeout")
end)
test("timeout also terminates children holding the output pipe", function()
	local path = file("child.py", {
		"import subprocess, sys, time",
		"subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(2)'])",
		"time.sleep(2)",
	})
	local started = vim.uv.hrtime()
	local result = run(path, "python", "", { timeout = 100 })
	eq(result.reason, "timeout")
	assert((vim.uv.hrtime() - started) / 1e6 < 1500, "child process kept the output pipe open after timeout")
end)
test("output is bounded", function()
	local path = file("flood.py", { "while True: print('x' * 4096, flush=True)" })
	local result = run(path, "python", "", { output_limit = 8192 })
	eq(result.reason, "output_limit")
	assert(#result.stdout + #result.stderr <= 8192)
end)
test("running process can be cancelled", function()
	local result
	local handle = runner.start(loop, "python", "", {}, function(value) result = value end)
	handle.cancel()
	assert(vim.wait(3000, function() return result ~= nil end))
	eq(result.reason, "cancelled")
end)
test("missing interpreter reports a useful error", function()
	local result = run(py, "python", "", { python = root .. "/missing-python" })
	assert(result.code ~= 0 and #result.stderr > 0)
end)
local ui = require("cp_runner")
ui.setup()
local source
test("unsupported suffix reports an error even with cpp filetype", function()
	vim.cmd.edit(vim.fn.fnameescape(file("unsupported.txt", { "test" })))
	vim.bo.filetype = "cpp"
	local original, message, level = vim.notify
	vim.notify = function(text, severity) message, level = text, severity end
	local session = ui.open()
	vim.notify = original
	if session then ui.close() end
	eq(session, nil)
	eq(level, vim.log.levels.ERROR)
	assert(message:find(".cpp", 1, true) and message:find(".py", 1, true))
end)
test("py suffix works even when filetype is unset", function()
	vim.cmd.edit(vim.fn.fnameescape(py))
	vim.bo.filetype = ""
	local session = ui.open()
	assert(session, "must detect the filename suffix")
	ui.run()
	assert(vim.wait(5000, function() return session.result ~= nil end))
	eq(session.result.stdout, "0\n")
	ui.close()
end)
test("opens editable input and read-only output side by side", function()
	vim.cmd.edit(vim.fn.fnameescape(py))
	vim.bo.filetype = "python"
	source = vim.api.nvim_get_current_buf()
	local session = ui.open()
	assert(session)
	assert(vim.bo[session.input_buf].modifiable)
	assert(not vim.bo[session.output_buf].modifiable)
	local left = vim.api.nvim_win_get_config(session.input_win)
	local right = vim.api.nvim_win_get_config(session.output_win)
	assert(left.col < right.col and left.row == right.row)
	vim.api.nvim_buf_set_lines(session.input_buf, 0, -1, false, { "5 6", "7" })
	ui.run()
	assert(vim.wait(5000, function() return session.result ~= nil end))
	eq(session.result.stdout, "18\n")
	eq(vim.api.nvim_get_current_buf(), session.input_buf)
	ui.close()
	eq(vim.api.nvim_get_current_buf(), source)
end)
test("input survives closing and reopening", function()
	local session = ui.open()
	eq(vim.api.nvim_buf_get_lines(session.input_buf, 0, -1, false), { "5 6", "7" })
	ui.close()
end)
test("run saves the original buffer even while focus is in input", function()
	vim.api.nvim_buf_set_lines(source, 0, -1, false, { "print('edited')" })
	local session = ui.open()
	ui.run()
	assert(vim.wait(5000, function() return session.result ~= nil end))
	eq(session.result.stdout, "edited\n")
	eq(vim.fn.readfile(py), { "print('edited')" })
	ui.close()
end)
test("closing either float cleans up both windows and buffers", function()
	local session = ui.open()
	vim.api.nvim_win_close(session.output_win, true)
	assert(vim.wait(1000, function() return not vim.api.nvim_win_is_valid(session.input_win) end))
	assert(not vim.api.nvim_buf_is_valid(session.output_buf))
	assert(not vim.api.nvim_buf_is_valid(session.input_buf))
end)
test("repeated run cannot be overwritten by a cancelled result", function()
	vim.api.nvim_buf_set_lines(source, 0, -1, false, { "while True: pass" })
	local session = ui.open()
	ui.run()
	vim.api.nvim_buf_set_lines(source, 0, -1, false, { "print('latest')" })
	ui.run()
	assert(vim.wait(5000, function() return session.result ~= nil end))
	eq(session.result.stdout, "latest\n")
	ui.close()
end)
test("renaming source to an unsupported suffix blocks subsequent runs", function()
	local session = ui.open()
	local api = vim.api
	api.nvim_buf_set_name(source, root .. "/renamed.txt")
	ui.run()
	eq(session.job, nil)
	assert(table.concat(api.nvim_buf_get_lines(session.output_buf, 0, -1, false)):find(".cpp", 1, true))
	ui.close()
	api.nvim_buf_set_name(source, py)
end)
test("input is isolated between source files", function()
	vim.cmd.edit(vim.fn.fnameescape(loop))
	local session = ui.open()
	eq(vim.api.nvim_buf_get_lines(session.input_buf, 0, -1, false), { "" })
	ui.close()
	vim.api.nvim_set_current_buf(source)
end)
test("resize keeps floats on screen", function()
	local session = ui.open()
	local columns = vim.o.columns
	vim.o.columns = 60
	vim.api.nvim_exec_autocmds("VimResized", {})
	local config = vim.api.nvim_win_get_config(session.output_win)
	assert(config.col + config.width + 2 <= 60)
	ui.close()
	vim.o.columns = columns
end)
test("closing while compiling cancels the job and removes its temporary directory", function()
	local cpp = root .. "/sum with spaces.cpp"
	vim.cmd.edit(vim.fn.fnameescape(cpp))
	local session = ui.open()
	ui.run()
	local handle = session.job
	assert(vim.fn.isdirectory(handle.temp_dir) == 1)
	ui.close()
	assert(vim.wait(5000, function() return vim.fn.isdirectory(handle.temp_dir) == 0 end))
	assert(not vim.api.nvim_buf_is_valid(session.output_buf))
end)
vim.fn.delete(root, "rf")
print(string.format("All %d tests passed", count))
vim.cmd("qa!")
